export type PaletteKey = keyof typeof colorPalettes;
export type ThemeMode = 'light' | 'dark';

export function applyPaletteToDOM(
  paletteKey: PaletteKey,
  appearanceMode: 'light' | 'dark' | 'standard'
) {
  const palette = colorPalettes[paletteKey];
  if (!palette) return;

  if (appearanceMode === 'standard') {
    // For standard mode: dark sidebar + light content
    const lightColors = palette.light;
    const darkColors = palette.dark;

    // Apply light mode colors for content
    Object.entries(lightColors).forEach(([key, value]) => {
      const cssVar = `--${key.replace(/_/g, '-')}`;
      document.documentElement.style.setProperty(cssVar, value, 'important');
    });

    // Override with dark sidebar colors
    Object.entries(darkColors).forEach(([key, value]) => {
      if (key.startsWith('sidebar_')) {
        const cssVar = `--${key.replace(/_/g, '-')}`;
        document.documentElement.style.setProperty(cssVar, value, 'important');
      }
    });
  } else {
    // For light/dark modes: use mode colors consistently
    const isDark = appearanceMode === 'dark';
    const mode: ThemeMode = isDark ? 'dark' : 'light';
    const colors = palette[mode];

    // Apply all color variables with !important to ensure they override .dark class variables
    Object.entries(colors).forEach(([key, value]) => {
      const cssVar = `--${key.replace(/_/g, '-')}`;
      document.documentElement.style.setProperty(cssVar, value, 'important');
    });
  }
}

export function getSelectedPaletteKey(): PaletteKey {
  const saved = localStorage.getItem('selectedPalette');
  return (saved as PaletteKey) || 'corporate';
}

export function saveSelectedPaletteKey(key: PaletteKey) {
  localStorage.setItem('selectedPalette', key);
}
