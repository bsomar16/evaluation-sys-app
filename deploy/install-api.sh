#!/bin/bash
# Deploys the SPA and the API to the cPanel document root of the subdomain.
#

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

DOCROOT="${EVAL_DOCROOT:?EVAL_DOCROOT is required}"
DB_NAME="${DB_NAME:?DB_NAME is required}"
DB_USER="${DB_USER:?DB_USER is required}"
DB_PASSWORD="${DB_PASSWORD:?DB_PASSWORD is required}"
DB_HOST="${DB_HOST:-127.0.0.1}"
DB_PORT="${DB_PORT:-5432}"
API_BASE="${API_BASE:-/}"

mkdir -p "$DOCROOT"

echo "=== 1/4 building the SPA (base=$API_BASE) ===="
APP_BASE="$API_BASE" npm run build

echo "=== 2/4 copying the build to the document root ===="
rm -rf "$DOCROOT/assets"
cp -r dist/. "$DOCROOT/"
chmod 644 "$DOCROOT/index.html" "$DOCROOT/.htaccess" 2>/dev/null || true

echo "=== 3/4 writing the API configuration (outside the document root) ===="
CONFIG_DIR="$(dirname "$DOCROOT")/.eval-api"
mkdir -p "$CONFIG_DIR"
chmod 700 "$CONFIG_DIR"
SECRET="${API_SECRET:-$(php -r 'echo bin2hex(random_bytes(32));')}"

cat > "$CONFIG_DIR/config.php" <<PHP
<?php
// Generated by deploy/install-api.sh - do not commit.
return [
    'dsn'      => 'pgsql:host=$DB_HOST;port=$DB_PORT;dbname=$DB_NAME',
    'user'     => '$DB_USER',
    'password' => '$DB_PASSWORD',
    'app_role' => 'app_api',
    'secret'   => '$SECRET',
];
PHP
chmod 600 "$CONFIG_DIR/config.php"
echo "    config written to $CONFIG_DIR/config.php"

echo "=== 4/4 checking the API ===="
php -l "$DOCROOT/rest/v1/api.php"

echo
echo "Done. Now:"
echo "  1. create the subdomain in cPanel -> Domains -> Subdomains (docroot: $DOCROOT)"
echo "  2. add an A record for the subdomain in Cloudflare -> $DB_HOST"
echo "  3. run:  PGPASSWORD=... ./deploy/sql/install.sh"
echo "  4. open https://<subdomain>/rest/v1/health"
